// DigiRoll bitmap format: C header export/import. Shared by the editor and gallery.
// A bitmap is { width, height, depth, pixels: Uint8Array of levels 0..2^depth-1 }.

// ---- Export / import format ----
//
// A C header with the size and depth as #defines plus a uint8_t array.
// Two layouts, recorded in a "// Layout: ..." comment so upload can read it back:
//
//   packed — row-major, top row first, left to right. Each pixel is DEPTH bits,
//            MSB first. Each row is padded to a whole number of bytes.
//   planar — DEPTH bit planes, most significant plane first. Each plane is a
//            1-bit image in the packed layout above. Suits bit-plane (BCM)
//            grayscale scanning, where each plane is shown for a weighted time.
//
// At 1-bit both layouts are identical: a 16x16 image is 2 bytes/row, 32 bytes.

const MAX_SIZE = 64;
const MAX_DEPTH = 4;
const LAYOUTS = ['packed', 'planar'];

const bytesPerRow = (width, bits) => Math.ceil((width * bits) / 8);

// Pack values of `bits` bits each into rows of bytes, MSB first.
function packBits(values, width, height, bits) {
  const bpr = bytesPerRow(width, bits);
  const bytes = new Uint8Array(bpr * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const v = values[y * width + x];
      for (let b = 0; b < bits; b++) {
        const bit = (v >> (bits - 1 - b)) & 1;
        const pos = x * bits + b;
        bytes[y * bpr + (pos >> 3)] |= bit << (7 - (pos & 7));
      }
    }
  }
  return bytes;
}

function unpackBits(bytes, width, height, bits) {
  const bpr = bytesPerRow(width, bits);
  const values = new Uint8Array(width * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      let v = 0;
      for (let b = 0; b < bits; b++) {
        const pos = x * bits + b;
        v = (v << 1) | ((bytes[y * bpr + (pos >> 3)] >> (7 - (pos & 7))) & 1);
      }
      values[y * width + x] = v;
    }
  }
  return values;
}

// Returns an array of byte chunks. Packed: one chunk. Planar: one per plane, MSB first.
function encode(pixels, width, height, depth, layout) {
  if (layout === 'packed') return [packBits(pixels, width, height, depth)];
  const planes = [];
  for (let bit = depth - 1; bit >= 0; bit--) {
    planes.push(packBits(pixels.map((v) => (v >> bit) & 1), width, height, 1));
  }
  return planes;
}

function decode(bytes, width, height, depth, layout) {
  if (layout === 'packed') return unpackBits(bytes, width, height, depth);
  const planeSize = bytesPerRow(width, 1) * height;
  const pixels = new Uint8Array(width * height);
  for (let p = 0; p < depth; p++) {
    const plane = unpackBits(bytes.subarray(p * planeSize, (p + 1) * planeSize), width, height, 1);
    const bit = depth - 1 - p;
    for (let i = 0; i < pixels.length; i++) pixels[i] |= plane[i] << bit;
  }
  return pixels;
}

const encodedSize = (width, height, depth, layout) => layout === 'packed'
  ? bytesPerRow(width, depth) * height
  : bytesPerRow(width, 1) * height * depth;

function toIdentifier(name) {
  let id = String(name).trim().replace(/[^A-Za-z0-9_]/g, '_');
  if (!id) id = 'bitmap';
  if (/^[0-9]/.test(id)) id = '_' + id;
  return id;
}

const hex = (b) => '0x' + b.toString(16).padStart(2, '0').toUpperCase();

function generateC(bitmap, name, layout) {
  const { width, height, depth, pixels } = bitmap;
  if (depth === 1) layout = 'packed';
  const id = toIdentifier(name);
  const macro = id.toUpperCase();
  const chunks = encode(pixels, width, height, depth, layout);
  const bits = layout === 'packed' ? depth : 1;
  const bpr = bytesPerRow(width, bits);
  const total = chunks.reduce((n, c) => n + c.length, 0);

  const body = [];
  chunks.forEach((chunk, p) => {
    if (layout === 'planar') {
      const bit = depth - 1 - p;
      body.push(`  // plane ${p}: bit ${bit} (weight ${1 << bit})`);
    }
    for (let y = 0; y < height; y++) {
      const row = Array.from(chunk.subarray(y * bpr, (y + 1) * bpr), hex);
      body.push(`  ${row.join(', ')}, // row ${y}`);
    }
  });

  const layoutDoc = layout === 'packed'
    ? [
      '// Layout: packed',
      '//   Row-major, top row first. Each pixel is DEPTH bits, MSB first.',
      '//   Each row is padded to a whole number of bytes.',
    ]
    : [
      '// Layout: planar',
      '//   DEPTH bit planes, most significant plane first. Each plane is a',
      '//   1-bit, row-major image (top row first, MSB = leftmost pixel),',
      `//   each row padded to whole bytes. ${macro}_PLANE_SIZE bytes per plane.`,
    ];

  return [
    '// Generated by the DigiRoll Bitmap Editor.',
    ...layoutDoc,
    '#pragma once',
    '#include <stdint.h>',
    '',
    `#define ${macro}_WIDTH ${width}`,
    `#define ${macro}_HEIGHT ${height}`,
    `#define ${macro}_DEPTH ${depth}`,
    ...(layout === 'planar' ? [`#define ${macro}_PLANE_SIZE ${chunks[0].length}`] : []),
    '',
    `static const uint8_t ${id}[${total}] = {`,
    ...body,
    '};',
    '',
  ].join('\n');
}

function parseC(text) {
  // Read the layout from its comment before comments are stripped. Default: packed.
  const lm = text.match(/Layout:\s*(packed|planar)/i);
  const layout = lm ? lm[1].toLowerCase() : 'packed';

  const src = text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

  const define = (suffix) => {
    const m = src.match(new RegExp(`#define\\s+\\w*?_?${suffix}\\s+(\\d+)\\b`));
    if (!m) throw new Error(`Missing #define …_${suffix}.`);
    return Number(m[1]);
  };
  const width = define('WIDTH');
  const height = define('HEIGHT');
  const depth = define('DEPTH');

  if (width < 1 || width > MAX_SIZE || height < 1 || height > MAX_SIZE) {
    throw new Error(`Width and height must be between 1 and ${MAX_SIZE}.`);
  }
  if (depth < 1 || depth > MAX_DEPTH) {
    throw new Error(`Depth must be between 1 and ${MAX_DEPTH}.`);
  }

  const arr = src.match(/(\w+)\s*\[\s*\w*\s*\]\s*=\s*\{([^}]*)\}/);
  if (!arr) throw new Error('Missing array initializer: name[] = { … };');

  const nums = (arr[2].match(/0x[0-9a-f]+|0b[01]+|\d+/gi) || []).map((t) =>
    t.toLowerCase().startsWith('0b') ? parseInt(t.slice(2), 2) : Number(t));
  if (nums.some((n) => Number.isNaN(n) || n > 255)) {
    throw new Error('Array values must be bytes (0–255).');
  }

  const expected = encodedSize(width, height, depth, layout);
  if (nums.length !== expected) {
    throw new Error(`Expected ${expected} bytes for ${width}×${height} at ${depth}-bit (${layout}), found ${nums.length}.`);
  }

  return {
    name: arr[1],
    layout,
    width,
    height,
    depth,
    pixels: decode(Uint8Array.from(nums), width, height, depth, layout),
  };
}
